CREATE TRIGGER IF NOT EXISTS trg_m_pod_supersession_guard_insert
BEFORE INSERT ON m_pod
WHEN NEW.superseded_by IS NOT NULL
BEGIN
    SELECT RAISE(ABORT, 'supersession cycle')
    WHERE EXISTS (
        WITH RECURSIVE supersession_chain(pod_id_seq) AS (
            SELECT NEW.superseded_by
            UNION
            SELECT pod.superseded_by
            FROM m_pod AS pod
            JOIN supersession_chain AS chain ON pod.pod_id_seq = chain.pod_id_seq
            WHERE pod.superseded_by IS NOT NULL
        )
        SELECT 1 FROM supersession_chain WHERE pod_id_seq = NEW.pod_id_seq
    );
    SELECT RAISE(ABORT, 'supersession must target a later POD')
    WHERE NOT EXISTS (
        SELECT 1
        FROM m_pod AS successor
        WHERE successor.pod_id_seq = NEW.superseded_by
          AND successor.approval_date > NEW.approval_date
    );
END;
CREATE TRIGGER IF NOT EXISTS trg_m_pod_supersession_guard_update
BEFORE UPDATE OF superseded_by ON m_pod
WHEN NEW.superseded_by IS NOT NULL
BEGIN
    SELECT RAISE(ABORT, 'supersession cycle')
    WHERE EXISTS (
        WITH RECURSIVE supersession_chain(pod_id_seq) AS (
            SELECT NEW.superseded_by
            UNION
            SELECT pod.superseded_by
            FROM m_pod AS pod
            JOIN supersession_chain AS chain ON pod.pod_id_seq = chain.pod_id_seq
            WHERE pod.superseded_by IS NOT NULL
        )
        SELECT 1 FROM supersession_chain WHERE pod_id_seq = NEW.pod_id_seq
    );
    SELECT RAISE(ABORT, 'supersession must target a later POD')
    WHERE NOT EXISTS (
        SELECT 1
        FROM m_pod AS successor
        WHERE successor.pod_id_seq = NEW.superseded_by
          AND successor.approval_date > NEW.approval_date
    );
END;
CREATE TRIGGER IF NOT EXISTS trg_pod_project_reference_insert BEFORE INSERT ON pod_project WHEN NOT EXISTS (SELECT 1 FROM m_pod WHERE pod_id_seq = NEW.pod_id_seq) OR NOT EXISTS (SELECT 1 FROM m_project WHERE project_id = NEW.project_id) BEGIN SELECT RAISE(ABORT, 'pod_project reference is missing'); END;
CREATE TRIGGER IF NOT EXISTS trg_pod_project_reference_update BEFORE UPDATE OF pod_id_seq, project_id ON pod_project WHEN NOT EXISTS (SELECT 1 FROM m_pod WHERE pod_id_seq = NEW.pod_id_seq) OR NOT EXISTS (SELECT 1 FROM m_project WHERE project_id = NEW.project_id) BEGIN SELECT RAISE(ABORT, 'pod_project reference is missing'); END;
