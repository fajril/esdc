CREATE TRIGGER IF NOT EXISTS trg_m_project_pod_project_no_delete BEFORE DELETE ON m_project WHEN EXISTS (SELECT 1 FROM pod_project WHERE project_id = OLD.project_id) BEGIN SELECT RAISE(ABORT, 'm_project is referenced by pod_project'); END;
